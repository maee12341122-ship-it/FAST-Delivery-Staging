-- FAST: امنية وتوافق مع الجداول اليدوية الحالية.
-- شغّل هذا الملف بعد أخذ نسخة احتياطية من Supabase.
create extension if not exists pgcrypto;

-- قيم افتراضية آمنة للمعرفات النصية الحالية دون تغيير نوعها.
create sequence if not exists public.customers_id_seq;
do $$ declare next_id bigint; begin
  select coalesce(max(id),0)+1 into next_id from public.customers;
  perform setval('public.customers_id_seq', greatest(next_id,1), false);
  alter table public.customers alter column id set default nextval('public.customers_id_seq');
end $$;
alter table public.products alter column id set default gen_random_uuid()::text;
alter table public.orders alter column id set default gen_random_uuid()::text;
alter table public.couriers alter column id set default gen_random_uuid()::text;

-- أعمدة تشغيلية اختيارية تستخدمها الإصدارات الحالية/القادمة.
alter table public.couriers add column if not exists auth_user_id uuid unique references auth.users(id) on delete set null;
alter table public.couriers add column if not exists onesignal_player_id text;
alter table public.customers add column if not exists onesignal_player_id text;
alter table public.orders add column if not exists payment_method text not null default 'cash_on_delivery';
alter table public.orders add column if not exists payment_status text not null default 'unpaid';
alter table public.orders add column if not exists payment_account text not null default '';
alter table public.orders add column if not exists notes text not null default '';
alter table public.orders add column if not exists created_at timestamptz not null default now();
alter table public.orders add column if not exists updated_at timestamptz not null default now();
alter table public.settings add column if not exists onesignal_player_id text;
alter table public.settings add column if not exists delivery_fee integer not null default 500;

-- منع تكرار رقم العميل عند وجود بيانات قديمة مكررة: افحص قبل إنشاء الفهرس.
update public.customers set phone = null where phone = '';
create unique index if not exists customers_phone_unique_idx
  on public.customers(phone);

-- جدول الرسائل الذي تتوقعه واجهة المحادثات.
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  order_id text not null references public.orders(id) on delete cascade,
  sender_type text not null check (sender_type in ('admin','courier','customer')),
  target_chat text not null check (target_chat in ('admin_customer','admin_courier')),
  message_text text not null check (length(trim(message_text)) between 1 and 4000),
  created_at timestamptz not null default now()
);

-- تفعيل RLS وإزالة السياسات المفتوحة القديمة على الجداول الحساسة.
alter table public.couriers enable row level security;
alter table public.customers enable row level security;
alter table public.orders enable row level security;
alter table public.products enable row level security;
alter table public.settings enable row level security;
alter table public.messages enable row level security;

do $$ declare p record; begin
  for p in select schemaname, tablename, policyname from pg_policies
    where schemaname='public' and tablename in ('couriers','customers','orders','products','settings','messages')
  loop execute format('drop policy if exists %I on %I.%I',p.policyname,p.schemaname,p.tablename); end loop;
end $$;

-- القراءة العامة مقتصرة على المنتجات المتاحة وإعدادات ساعات العمل.
create policy fast_public_products_read on public.products for select to anon, authenticated using (available is true);
create policy fast_public_settings_read on public.settings for select to anon, authenticated using (true);

-- دور المدير يضاف إلى app_metadata بواسطة مسؤول موثوق (موضح في README_DEPLOY_AR.md).
create policy fast_admin_products_all on public.products for all to authenticated
  using ((auth.jwt()->'app_metadata'->>'role')='admin')
  with check ((auth.jwt()->'app_metadata'->>'role')='admin');
create policy fast_admin_couriers_all on public.couriers for all to authenticated
  using ((auth.jwt()->'app_metadata'->>'role')='admin')
  with check ((auth.jwt()->'app_metadata'->>'role')='admin');
create policy fast_admin_customers_read on public.customers for select to authenticated
  using ((auth.jwt()->'app_metadata'->>'role')='admin');
create policy fast_admin_customers_update on public.customers for update to authenticated
  using ((auth.jwt()->'app_metadata'->>'role')='admin')
  with check ((auth.jwt()->'app_metadata'->>'role')='admin');
create policy fast_admin_orders_all on public.orders for all to authenticated
  using ((auth.jwt()->'app_metadata'->>'role')='admin')
  with check ((auth.jwt()->'app_metadata'->>'role')='admin');
create policy fast_admin_settings_all on public.settings for all to authenticated
  using ((auth.jwt()->'app_metadata'->>'role')='admin')
  with check ((auth.jwt()->'app_metadata'->>'role')='admin');

-- المندوب يرى طلباته فقط. لا نعطيه سياسة تحديث عامة على الطلبات حتى لا يغير الأسعار أو المبالغ.
create policy fast_courier_own_profile_read on public.couriers for select to authenticated
  using (auth_user_id = auth.uid());
create policy fast_courier_assigned_orders_read on public.orders for select to authenticated
  using (assigned_courier = (select c.name from public.couriers c where c.auth_user_id=auth.uid() limit 1));

create policy fast_admin_messages_all on public.messages for all to authenticated
  using ((auth.jwt()->'app_metadata'->>'role')='admin')
  with check ((auth.jwt()->'app_metadata'->>'role')='admin');
create policy fast_courier_assigned_messages_read on public.messages for select to authenticated
  using (exists (select 1 from public.orders o join public.couriers c on c.name=o.assigned_courier
    where o.id=messages.order_id and c.auth_user_id=auth.uid()));
create policy fast_courier_assigned_messages_insert on public.messages for insert to authenticated
  with check (sender_type='courier' and exists (
    select 1 from public.orders o join public.couriers c on c.name=o.assigned_courier
    where o.id=messages.order_id and c.auth_user_id=auth.uid()));

-- العملاء لا يملكون جلسات Auth في هذا الإصدار؛ لا نفتح إدخال الطلبات أو بيانات العملاء للـ anon.
