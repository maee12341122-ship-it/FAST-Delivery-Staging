-- لا توجد سياسات عامة لهذا الجدول؛ لا يقرأه أو يكتب فيه إلا Edge Functions باستخدام service role.
alter table public.orders add column if not exists cash_collected_by uuid references auth.users(id);
alter table public.orders add column if not exists cash_collected_at timestamptz;

-- كلمات المرور القديمة في جدول المندوبين كانت نصاً مكشوفاً؛ الحسابات الجديدة تستخدم Supabase Auth.
update public.couriers set password = null where password is not null;

-- توحيد طريقة الدفع للمرحلة الأولى فقط.
update public.orders set payment_method = 'cash_on_delivery'
where payment_method is null or payment_method not in ('cash_on_delivery','cash');
update public.orders set payment_method = 'cash_on_delivery' where payment_method = 'cash';
update public.orders set payment_status = 'unpaid' where payment_status is null or payment_status not in ('unpaid','collected');

do $$ begin
  if not exists (select 1 from pg_constraint where conname='orders_payment_method_fast_check') then
    alter table public.orders add constraint orders_payment_method_fast_check check (payment_method='cash_on_delivery');
  end if;
  if not exists (select 1 from pg_constraint where conname='orders_payment_status_fast_check') then
    alter table public.orders add constraint orders_payment_status_fast_check check (payment_status in ('unpaid','collected'));
  end if;
end $$;
